// 1Password: agents look up and rotate credentials in the vaults you choose,
// without an `op` session of their own. It talks to a 1Password Connect
// server, whose token is limited to those vaults.
//
// Secrets: OP_CONNECT_HOST (https address of the Connect server), OP_CONNECT_TOKEN.
// Optional, when the server sits behind Cloudflare Access: CF_ACCESS_CLIENT_ID,
// CF_ACCESS_CLIENT_SECRET (an Access service token).
//
// Listing and metadata run freely and never include a value. Reading a value
// into the agent's conversation, creating an item and every rotation write ask
// the user first. No tool takes a secret: new values are generated by
// 1Password, or copied from one field to another inside it.

async function op(env, method, path, body) {
  const host = String(env.OP_CONNECT_HOST || "").replace(/\/+$/, "");
  if (!host.startsWith("https://")) throw new Error("OP_CONNECT_HOST must be an https:// address");
  const res = await fetch(host + "/v1" + path, {
    method,
    headers: {
      Authorization: "Bearer " + env.OP_CONNECT_TOKEN,
      "Content-Type": "application/json",
      ...(env.CF_ACCESS_CLIENT_ID && { "CF-Access-Client-Id": env.CF_ACCESS_CLIENT_ID, "CF-Access-Client-Secret": env.CF_ACCESS_CLIENT_SECRET }),
    },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const json = await res.json().catch(() => null);
  if (!res.ok) throw new Error("1Password: " + ((json && json.message) || "HTTP " + res.status));
  return json;
}

// A vault or item by its id, or by its exact name when exactly one has it.
async function find(env, path, key, name, kind) {
  if (/^[a-z0-9]{26}$/.test(name || "")) return op(env, "GET", path + "/" + name);
  if (typeof name !== "string" || !name || name.includes('"')) throw new Error("Name the " + kind + " by its title or id");
  const found = await op(env, "GET", path + "?filter=" + encodeURIComponent(key + ' eq "' + name + '"'));
  if (found.length !== 1) throw new Error(found.length ? "More than one " + kind + ' is called "' + name + '"; use its id' : "No " + kind + ' called "' + name + '"');
  return found[0];
}
const vaultOf = (env, vault) => find(env, "/vaults", "name", vault, "vault");
async function itemOf(env, input) {
  const vault = await vaultOf(env, input.vault);
  const path = "/vaults/" + vault.id + "/items";
  const summary = await find(env, path, "title", input.item, "item");
  return { vault, path: path + "/" + summary.id, item: await op(env, "GET", path + "/" + summary.id) };
}
function fieldOf(item, name) {
  const matches = (item.fields || []).filter((f) => f.id === name || f.label === name);
  if (matches.length > 1) throw new Error('More than one field is called "' + name + '"; use its id from get_item');
  return matches[0];
}
const where = (found) => 'item "' + found.item.title + '" in vault "' + found.vault.name + '"';

// What an agent may see without asking: everything about an item except what its fields hold.
const summary = (i) => ({ id: i.id, title: i.title, category: i.category, tags: i.tags || [], urls: (i.urls || []).map((u) => u.href), updated: i.updatedAt });
const recipe = ({ length, symbols }) => ({ length: Math.max(12, Math.min(64, Math.round(length || 32))), characterSets: ["LETTERS", "DIGITS", ...(symbols === false ? [] : ["SYMBOLS"])] });

const target = { vault: { type: "string", description: "Vault name or id" }, item: { type: "string", description: "Item title or id" } };
const obj = (properties, required = Object.keys(properties)) => ({ type: "object", properties, required });
const generated = { length: { type: "number", description: "12 to 64, default 32" }, symbols: { type: "boolean", description: "false for sites that reject symbols" } };

export const tools = {
  list_vaults: {
    description: "The vaults this integration can reach.",
    input: { type: "object" },
    run: async (_, env) => (await op(env, "GET", "/vaults")).map((v) => ({ id: v.id, name: v.name, items: v.items })),
  },
  list_items: {
    description: "Items in a vault, oldest edit first: titles, categories, tags, addresses and when each was last changed. Never a value.",
    input: obj({ vault: target.vault, search: { type: "string", description: "Keep items whose title contains this" } }, ["vault"]),
    async run({ vault, search }, env) {
      const items = await op(env, "GET", "/vaults/" + (await vaultOf(env, vault)).id + "/items");
      const q = String(search || "").toLowerCase();
      return items.filter((i) => i.title.toLowerCase().includes(q)).map(summary).sort((a, b) => String(a.updated).localeCompare(String(b.updated)));
    },
  },
  get_item: {
    description: "One item's details and the names and kinds of its fields. The username is included; no other field's value is.",
    input: obj(target),
    async run(input, env) {
      const { item } = await itemOf(env, input);
      return { ...summary(item), fields: (item.fields || []).map((f) => ({ id: f.id, label: f.label, type: f.type, purpose: f.purpose, ...(f.purpose === "USERNAME" && { value: f.value }), filled: Boolean(f.value) })) };
    },
  },
  read_secret: {
    description: "Read the value of one field. It ends up in your conversation, so the user is asked first. Prefer generate_field and copy_field, which rotate without showing a value to anyone.",
    input: obj({ ...target, field: { type: "string", description: "Field label or id, e.g. password" } }),
    async approval(input, env) {
      const found = await itemOf(env, input);
      if (!fieldOf(found.item, input.field)) throw new Error('No field called "' + input.field + '"');
      return `Show the agent the value of "${input.field}" from ${where(found)}. It will be in the agent's conversation.`;
    },
    async run(input, env) {
      return (fieldOf((await itemOf(env, input)).item, input.field) || {}).value;
    },
  },
  create_item: {
    description: "Create a login item, optionally with a password 1Password generates. Asks the user first.",
    input: obj({ vault: target.vault, title: { type: "string" }, username: { type: "string" }, url: { type: "string" }, tags: { type: "array", items: { type: "string" } }, generate_password: { type: "boolean" }, ...generated }, ["vault", "title"]),
    approval: async (input, env) => `Create the item "${input.title}" in vault "${(await vaultOf(env, input.vault)).name}"${input.generate_password ? " with a generated password" : ""}.`,
    async run(input, env) {
      const vault = await vaultOf(env, input.vault);
      const made = await op(env, "POST", "/vaults/" + vault.id + "/items", {
        vault: { id: vault.id },
        title: input.title,
        category: "LOGIN",
        tags: input.tags || [],
        urls: input.url ? [{ primary: true, href: input.url }] : [],
        fields: [
          ...(input.username ? [{ id: "username", label: "username", type: "STRING", purpose: "USERNAME", value: input.username }] : []),
          ...(input.generate_password ? [{ id: "password", label: "password", type: "CONCEALED", purpose: "PASSWORD", generate: true, recipe: recipe(input) }] : []),
        ],
      });
      return summary(made);
    },
  },
  generate_field: {
    description:
      'Put a newly generated value in a field, creating the field if the item has none by that name. Nobody sees the value. To rotate a website password safely, generate into a spare field such as "staged password", set it on the site, then copy_field it over "password". Asks the user first.',
    input: obj({ ...target, field: { type: "string" }, ...generated }, ["vault", "item", "field"]),
    async approval(input, env) {
      const found = await itemOf(env, input);
      const old = fieldOf(found.item, input.field);
      return `${old && old.value ? "Replace" : "Set"} "${input.field}" of ${where(found)} with a newly generated value.${old && old.value ? " The old value stays in the item's history." : ""}`;
    },
    async run(input, env) {
      const { item, path } = await itemOf(env, input);
      const old = fieldOf(item, input.field);
      const fresh = { type: "CONCEALED", ...old, label: old ? old.label : input.field, value: undefined, generate: true, recipe: recipe(input) };
      const fields = old ? item.fields.map((f) => (f === old ? fresh : f)) : [...(item.fields || []), fresh];
      return summary(await op(env, "PUT", path, { ...item, fields }));
    },
  },
  copy_field: {
    description: 'Copy one field\'s value over another inside the same item, e.g. from "staged password" to "password" once the site has accepted it. Nobody sees the value. Asks the user first.',
    input: obj({ ...target, from: { type: "string" }, to: { type: "string" } }),
    async approval(input, env) {
      const found = await itemOf(env, input);
      for (const name of [input.from, input.to]) if (!fieldOf(found.item, name)) throw new Error('No field called "' + name + '"');
      return `Copy "${input.from}" over "${input.to}" in ${where(found)}. The old value stays in the item's history.`;
    },
    async run(input, env) {
      const { item, path } = await itemOf(env, input);
      const from = fieldOf(item, input.from), to = fieldOf(item, input.to);
      if (!from || !from.value || !to) throw new Error("Both fields must exist and the first must hold a value");
      return summary(await op(env, "PUT", path, { ...item, fields: item.fields.map((f) => (f === to ? { ...to, value: from.value } : f)) }));
    },
  },
};
